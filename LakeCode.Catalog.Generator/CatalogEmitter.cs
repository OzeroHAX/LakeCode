using System.Text;
using System.Text.Json;

namespace LakeCode.Catalog.Generator;

internal readonly record struct EmittedCatalog(string Source, int Providers, int Models);

/// <summary>Projects the models.dev JSON document into the C# catalog source.</summary>
internal static class CatalogEmitter
{
    public static EmittedCatalog Emit(byte[] json, string sourceUrl)
    {
        using var document = JsonDocument.Parse(json);
        var root = document.RootElement;
        if (root.ValueKind != JsonValueKind.Object)
            throw new InvalidDataException("models.dev root must be a JSON object.");

        var providers = new List<Provider>();
        var providerIds = new HashSet<string>(StringComparer.Ordinal);
        foreach (var property in root.EnumerateObject())
        {
            if (!providerIds.Add(property.Name))
                throw new InvalidDataException($"duplicate provider ID {property.Name}.");
            var provider = property.Value;
            if (provider.ValueKind != JsonValueKind.Object)
                throw new InvalidDataException($"provider {property.Name} is not an object.");
            if (!provider.TryGetProperty("models", out var models) || models.ValueKind != JsonValueKind.Object)
                throw new InvalidDataException($"provider {property.Name} has no models object.");

            var usable = new List<Model>();
            var modelIds = new HashSet<string>(StringComparer.Ordinal);
            foreach (var modelProperty in models.EnumerateObject())
            {
                if (!modelIds.Add(modelProperty.Name))
                    throw new InvalidDataException($"duplicate model ID {property.Name}/{modelProperty.Name}.");
                if (IsUsable(modelProperty.Value)) usable.Add(new Model(modelProperty.Name, modelProperty.Value));
            }
            if (usable.Count == 0) continue;

            usable.Sort(static (left, right) => string.CompareOrdinal(left.Id, right.Id));
            providers.Add(new Provider(property.Name, provider, usable));
        }

        providers.Sort(static (left, right) => string.CompareOrdinal(left.Id, right.Id));
        var modelCount = providers.Sum(provider => provider.Models.Count);
        var builder = new StringBuilder(2_000_000);
        AppendHeader(builder, sourceUrl, root.EnumerateObject().Count(), providers.Count, modelCount);
        AppendTypes(builder);
        AppendCatalog(builder, providers);
        return new EmittedCatalog(builder.ToString(), providers.Count, modelCount);
    }

    private static void AppendHeader(StringBuilder builder, string sourceUrl, int snapshotProviders, int providers, int models)
    {
        var label = sourceUrl.Replace('\r', ' ').Replace('\n', ' ');
        Line(builder, "// <auto-generated>");
        Line(builder, $"// Generated by LakeCode.Catalog.Generator from {label}.");
        Line(builder, "// Data: https://models.dev (MIT License; see LakeCode.Catalog.Generator/THIRD-PARTY-NOTICES.md).");
        Line(builder, $"// Snapshot entries: {snapshotProviders} providers; generated entries: {providers} providers, {models} models.");
        Line(builder, "// Filter: tool-capable models with text output and positive token limits.");
        Line(builder, "// </auto-generated>");
        Line(builder);
        Line(builder, "#nullable enable");
        Line(builder);
        Line(builder, "using System.Collections.Frozen;");
        Line(builder, "using System.Collections.Immutable;");
        Line(builder);
        Line(builder, "namespace LakeCode.Core.Providers;");
        Line(builder);
    }

    private static void AppendTypes(StringBuilder builder)
    {
        Line(builder, "/// <summary>models.dev provider snapshot entry. Data only; transport selection stays in the runtime.</summary>");
        Line(builder, "public sealed record ModelsDevProvider(");
        Line(builder, "    string Id,");
        Line(builder, "    string Name,");
        Line(builder, "    string? Package,");
        Line(builder, "    string? BaseUrl,");
        Line(builder, "    string? DocumentationUrl,");
        Line(builder, "    ImmutableArray<string> EnvironmentVariables,");
        Line(builder, "    ImmutableDictionary<string, ModelsDevModel> Models);");
        Line(builder);
        Line(builder, "/// <summary>models.dev model entry with normalized token limits.</summary>");
        Line(builder, "public sealed record ModelsDevModel(");
        Line(builder, "    string Id,");
        Line(builder, "    string Name,");
        Line(builder, "    string? Family,");
        Line(builder, "    string? Status,");
        Line(builder, "    int ContextWindowTokens,");
        Line(builder, "    int MaxInputTokens,");
        Line(builder, "    int MaxOutputTokens,");
        Line(builder, "    ImmutableArray<string> InputModalities,");
        Line(builder, "    ImmutableArray<string> OutputModalities,");
        Line(builder, "    ImmutableArray<ModelsDevReasoningOption> ReasoningOptions,");
        Line(builder, "    bool ToolCall,");
        Line(builder, "    bool Attachment,");
        Line(builder, "    bool Reasoning);");
        Line(builder);
        Line(builder, "/// <summary>models.dev reasoning control: effort values, a token budget, or a toggle.</summary>");
        Line(builder, "public sealed record ModelsDevReasoningOption(");
        Line(builder, "    string Type,");
        Line(builder, "    ImmutableArray<string> Values,");
        Line(builder, "    int? Min = null,");
        Line(builder, "    int? Max = null);");
        Line(builder);
        Line(builder, "/// <summary>Provider-aware catalog generated from models.dev. Models are filtered to tool-capable text chat.</summary>");
        Line(builder, "public static partial class ModelsDevCatalog");
        Line(builder, "{");
    }

    private static void AppendCatalog(StringBuilder builder, List<Provider> providers)
    {
        Line(builder, "    public static FrozenDictionary<string, ModelsDevProvider> Providers { get; } =");
        Line(builder, "        new Dictionary<string, ModelsDevProvider>(StringComparer.Ordinal)");
        Line(builder, "        {");
        foreach (var provider in providers)
        {
            Line(builder, $"            [{Quote(provider.Id)}] = new(");
            Line(builder, $"                {Quote(provider.Id)},");
            Line(builder, $"                {Quote(GetString(provider.Value, "name") ?? provider.Id)},");
            Line(builder, $"                {Quote(GetString(provider.Value, "npm"))},");
            Line(builder, $"                {Quote(GetString(provider.Value, "api"))},");
            Line(builder, $"                {Quote(GetString(provider.Value, "doc"))},");
            Line(builder, $"                {StringArray(GetStringArray(provider.Value, "env"))},");
            Line(builder, "                new Dictionary<string, ModelsDevModel>(StringComparer.Ordinal)");
            Line(builder, "                {");
            foreach (var model in provider.Models)
                Line(builder, $"                    [{Quote(model.Id)}] = {RenderModel(model.Id, model.Value)},");
            Line(builder, "                }.ToImmutableDictionary(StringComparer.Ordinal)),");
        }
        Line(builder, "        }.ToFrozenDictionary(StringComparer.Ordinal);");
        Line(builder);
        Line(builder, "    public static ModelsDevProvider? FindProvider(string providerId) =>");
        Line(builder, "        Providers.TryGetValue(providerId, out var provider) ? provider : null;");
        Line(builder);
        Line(builder, "    public static ModelsDevModel? FindModel(string providerId, string modelId) =>");
        Line(builder, "        Providers.TryGetValue(providerId, out var provider) && provider.Models.TryGetValue(modelId, out var model)");
        Line(builder, "            ? model");
        Line(builder, "            : null;");
        Line(builder, "}");
    }

    private static string RenderModel(string modelId, JsonElement model)
    {
        var (context, maximumInput, output) = NormalizeLimits(model);
        var modalities = model.TryGetProperty("modalities", out var value) && value.ValueKind == JsonValueKind.Object
            ? value
            : default;
        return $"new({Quote(modelId)}, {Quote(GetString(model, "name") ?? modelId)}, " +
               $"{Quote(GetString(model, "family"))}, {Quote(GetString(model, "status"))}, " +
               $"{context}, {maximumInput}, {output}, " +
               $"{StringArray(GetStringArray(modalities, "input"))}, {StringArray(GetStringArray(modalities, "output"))}, " +
               $"{ReasoningArray(model)}, {Bool(GetBool(model, "tool_call"))}, " +
               $"{Bool(GetBool(model, "attachment"))}, {Bool(GetBool(model, "reasoning"))})";
    }

    private static string ReasoningArray(JsonElement model)
    {
        if (!model.TryGetProperty("reasoning_options", out var options) || options.ValueKind != JsonValueKind.Array)
            return "[]";
        var values = new List<string>();
        foreach (var option in options.EnumerateArray()) values.Add(RenderReasoningOption(option));
        return "[" + string.Join(", ", values) + "]";
    }

    private static string RenderReasoningOption(JsonElement option)
    {
        var type = GetString(option, "type") ?? "";
        var values = StringArray(GetStringArray(option, "values"));
        var minimum = NullableInt(GetInt64OrNull(option, "min"));
        var maximum = NullableInt(GetInt64OrNull(option, "max"));
        return $"new({Quote(type)}, {values}, {minimum}, {maximum})";
    }

    private static (int Context, int MaximumInput, int Output) NormalizeLimits(JsonElement model)
    {
        if (!model.TryGetProperty("limit", out var limits) || limits.ValueKind != JsonValueKind.Object)
            return (1, 1, 1);
        var context = Clamp(GetInt64(limits, "context"), 1, int.MaxValue);
        var output = Clamp(GetInt64(limits, "output"), 1, context);
        var maximumInput = limits.TryGetProperty("input", out var input) && input.ValueKind == JsonValueKind.Number
            ? Clamp(input.GetInt64(), 1, context)
            : context;
        return (context, maximumInput, output);
    }

    private static bool IsUsable(JsonElement model)
    {
        if (!GetBool(model, "tool_call")) return false;
        if (!model.TryGetProperty("modalities", out var modalities) || modalities.ValueKind != JsonValueKind.Object ||
            !modalities.TryGetProperty("output", out var output) || output.ValueKind != JsonValueKind.Array ||
            !output.EnumerateArray().Any(value => value.ValueKind == JsonValueKind.String && value.GetString() == "text"))
            return false;
        if (!model.TryGetProperty("limit", out var limits) || limits.ValueKind != JsonValueKind.Object)
            return false;
        return GetInt64(limits, "context") > 0 && GetInt64(limits, "output") > 0;
    }

    private static int Clamp(long value, int minimum, int maximum) =>
        value < minimum ? minimum : value > maximum ? maximum : (int)value;

    private static bool GetBool(JsonElement element, string name) =>
        element.ValueKind == JsonValueKind.Object &&
        element.TryGetProperty(name, out var value) && value.ValueKind == JsonValueKind.True;

    private static long GetInt64(JsonElement element, string name) =>
        element.ValueKind == JsonValueKind.Object && element.TryGetProperty(name, out var value) &&
        value.ValueKind == JsonValueKind.Number ? value.GetInt64() : 0;

    private static long? GetInt64OrNull(JsonElement element, string name) =>
        element.ValueKind == JsonValueKind.Object && element.TryGetProperty(name, out var value) &&
        value.ValueKind == JsonValueKind.Number ? value.GetInt64() : null;

    private static string? GetString(JsonElement element, string name) =>
        element.ValueKind == JsonValueKind.Object && element.TryGetProperty(name, out var value) &&
        value.ValueKind == JsonValueKind.String ? value.GetString() : null;

    private static List<string> GetStringArray(JsonElement element, string name)
    {
        var values = new List<string>();
        if (element.ValueKind != JsonValueKind.Object || !element.TryGetProperty(name, out var array) ||
            array.ValueKind != JsonValueKind.Array)
            return values;
        foreach (var item in array.EnumerateArray())
        {
            if (item.ValueKind == JsonValueKind.String && item.GetString() is { } value) values.Add(value);
        }
        return values;
    }

    private static string StringArray(List<string> values) =>
        "[" + string.Join(", ", values.Select(Quote)) + "]";

    private static string NullableInt(long? value) => value?.ToString(System.Globalization.CultureInfo.InvariantCulture) ?? "null";

    private static string Bool(bool value) => value ? "true" : "false";

    private static string Quote(string? value) => value is null ? "null" : JsonSerializer.Serialize(value);

    private static void Line(StringBuilder builder, string text = "") => builder.Append(text).Append('\n');

    private sealed record Provider(string Id, JsonElement Value, List<Model> Models);

    private sealed record Model(string Id, JsonElement Value);
}

internal static class CatalogWriter
{
    public static bool WriteIfChanged(string path, string source)
    {
        var bytes = Encoding.UTF8.GetBytes(source);
        var fullPath = Path.GetFullPath(path);
        if (File.Exists(fullPath) && File.ReadAllBytes(fullPath).AsSpan().SequenceEqual(bytes)) return false;

        Directory.CreateDirectory(Path.GetDirectoryName(fullPath)!);
        var temporary = Path.Combine(Path.GetDirectoryName(fullPath)!, $".{Path.GetFileName(fullPath)}.{Guid.NewGuid():N}.tmp");
        try
        {
            File.WriteAllBytes(temporary, bytes);
            File.Move(temporary, fullPath, overwrite: true);
        }
        finally
        {
            if (File.Exists(temporary)) File.Delete(temporary);
        }
        return true;
    }
}
